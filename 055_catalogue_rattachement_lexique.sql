  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  % profil(s) au libellé non couvert : %', n, l; END IF;
  RAISE NOTICE '[OK]     62 libellés, catégories autorisées, tous les profils couverts';
END $c$;

