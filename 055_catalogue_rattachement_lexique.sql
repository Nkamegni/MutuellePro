CREATE TEMP TABLE _fusion AS
SELECT id_vehicule_catalogue AS id_doublon, id_conserve FROM (
  SELECT id_vehicule_catalogue,
         min(id_vehicule_catalogue) OVER (PARTITION BY vin, marque, modele, id_terme_vehicule, avec_remorque,
                                          avec_double_commande, avec_double_cabine, code_categorie_suggeree,
                                          energie, puissance, charge_utile, nombre_places) AS id_conserve
    FROM catalogue.vehicule_catalogue) x
 WHERE id_vehicule_catalogue <> id_conserve;
SELECT count(*) AS doublons_fusionnes FROM _fusion;

