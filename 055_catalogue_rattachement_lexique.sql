CREATE FUNCTION referentiel.fn_normaliser_libelle(p_libelle text) RETURNS text
LANGUAGE sql IMMUTABLE AS $f$
  SELECT btrim(regexp_replace(regexp_replace(
           translate(lower(coalesce(p_libelle, '')), 'àâäéèêëîïôöùûüç', 'aaaeeeeiioouuuc'),
           '\d+\s*places?', '', 'g'),
           '\s+', ' ', 'g'))
$f$;
COMMENT ON FUNCTION referentiel.fn_normaliser_libelle(text) IS
  'Clé de rapprochement d un libellé : minuscules, sans accents, espaces réduits.';

