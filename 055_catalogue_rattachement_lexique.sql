                        AND (k.double_commande IS NULL
                             OR k.double_commande = CASE WHEN c.avec_double_commande THEN 'Avec' ELSE 'Sans' END));
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  catégorie suggérée non autorisée : %', l; END IF;
  -- un terme directif impose sa catégorie
  SELECT count(*), string_agg(c.libelle_source, ', ') INTO n, l
    FROM referentiel.correspondance_libelle_vehicule c JOIN referentiel.terme_vehicule t USING (id_terme_vehicule)
   WHERE t.code_categorie_imposee IS NOT NULL AND c.code_categorie_suggeree IS DISTINCT FROM t.code_categorie_imposee;
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  catégorie contraire au terme directif : %', l; END IF;
