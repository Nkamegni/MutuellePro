CREATE VIEW catalogue.profil_vehicule AS
SELECT v.id_vehicule_catalogue, v.vin, v.wmi, v.marque, v.modele,
       g.libelle AS genre, t.libelle AS terme_vehicule, v.code_categorie_suggeree,
       v.avec_remorque, v.avec_double_commande, v.avec_double_cabine,
       v.energie, v.puissance, v.charge_utile, v.nombre_places, v.taille_vin, v.date_creation, v.id_terme_vehicule
  FROM catalogue.vehicule_catalogue v
  JOIN referentiel.terme_vehicule t USING (id_terme_vehicule)
  JOIN tarification.genre g ON g.id_genre = t.id_genre;
COMMENT ON VIEW catalogue.profil_vehicule IS 'Profil de véhicule lu par l API : genre canonique, terme, attributs, catégorie suggérée.';

CREATE VIEW catalogue.vehicules_catalogue AS
SELECT id_vehicule_catalogue AS id, vin, wmi, marque, modele, genre, energie, puissance,
       charge_utile, nombre_places, taille_vin, date_creation
  FROM catalogue.profil_vehicule;
COMMENT ON VIEW catalogue.vehicules_catalogue IS
  'TRANSITOIRE (07/10/2026) : ancien nom pour un server.js non corrigé. À supprimer après réconciliation Git.';

