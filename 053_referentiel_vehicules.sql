DROP TABLE site.genres_etats;
DROP TABLE site.carrosserie_usage_combinaisons;
DROP TABLE site.genres_usages;
DROP TABLE site.carrosseries;

CREATE VIEW site.carrosseries AS
SELECT t.id_terme_vehicule AS id, t.libelle AS nom, g.libelle AS genre_canonique, t.actif, t.ordre_affichage
  FROM referentiel.terme_vehicule t JOIN tarification.genre g USING (id_genre);

CREATE VIEW site.genres_etats AS
SELECT ta.id_terme_vehicule_attribut AS id, t.libelle AS alias, a.libelle AS etat_nom, a.valeurs AS etat_options,
       ta.actif, ta.ordre_affichage
  FROM referentiel.terme_vehicule_attribut ta
  JOIN referentiel.terme_vehicule t USING (id_terme_vehicule)
  JOIN referentiel.attribut_vehicule a USING (code_attribut_vehicule);

CREATE VIEW site.carrosserie_usage_combinaisons AS
SELECT min(c.id_combinaison_categorie) AS id, t.libelle AS carrosserie, c.double_commande, c.matiere_inflammable,
       jsonb_agg(c.code_categorie ORDER BY c.code_categorie) FILTER (WHERE c.code_categorie IS NOT NULL) AS codes_categorie,
       bool_and(c.actif) AS actif, min(c.ordre_affichage) AS ordre_affichage
  FROM referentiel.combinaison_categorie c JOIN referentiel.terme_vehicule t USING (id_terme_vehicule)
 GROUP BY t.libelle, c.double_commande, c.matiere_inflammable;

CREATE VIEW site.genres_usages AS
SELECT u.id_usage_genre AS id, g.libelle AS genre_canonique, u.libelle_usage AS usage_libelle, u.code_categorie,
       u.ordre_affichage, u.actif
  FROM referentiel.usage_genre u JOIN tarification.genre g USING (id_genre);

COMMENT ON VIEW site.carrosseries IS 'COMPATIBILITÉ (lot 2) : lecture du lexique referentiel.terme_vehicule pour le devis.';
COMMENT ON VIEW site.genres_etats IS 'COMPATIBILITÉ (lot 2) : lecture de referentiel.terme_vehicule_attribut.';
COMMENT ON VIEW site.carrosserie_usage_combinaisons IS 'COMPATIBILITÉ (lot 2) : lecture de referentiel.combinaison_categorie.';
COMMENT ON VIEW site.genres_usages IS 'COMPATIBILITÉ (lot 2) : lecture de referentiel.usage_genre.';

\echo '=== 9. Droits de lecture du compte applicatif ==='
GRANT USAGE ON SCHEMA referentiel TO mutuellepro;
GRANT SELECT ON ALL TABLES IN SCHEMA referentiel TO mutuellepro;
GRANT SELECT ON site.carrosseries, site.genres_etats, site.carrosserie_usage_combinaisons, site.genres_usages TO mutuellepro;
DO $d$
BEGIN
  IF NOT has_table_privilege('mutuellepro', 'site.carrosseries', 'SELECT')
     OR NOT has_table_privilege('mutuellepro', 'site.genres_usages', 'SELECT')
     OR NOT has_table_privilege('mutuellepro', 'referentiel.terme_vehicule', 'SELECT') THEN
    RAISE EXCEPTION '[ÉCHEC]  droits de lecture manquants pour mutuellepro';
  END IF;
  RAISE NOTICE '[OK]     Droits de lecture accordés à mutuellepro';
END $d$;

\echo '=== 10. Ce que reçoit le devis APRÈS : différences (seules les corrections décidées doivent apparaître) ==='
CREATE TEMP TABLE _api_apres AS
SELECT 'carrosseries' AS jeu, row_to_json(x)::text AS ligne FROM (SELECT nom, genre_canonique FROM site.carrosseries WHERE actif = true) x
UNION ALL SELECT 'genres_etats', row_to_json(x)::text FROM (SELECT alias, etat_nom, etat_options FROM site.genres_etats WHERE actif = true) x
UNION ALL SELECT 'genres_usages', row_to_json(x)::text FROM (SELECT genre_canonique, usage_libelle, code_categorie FROM site.genres_usages WHERE actif = true) x
UNION ALL SELECT 'combinaisons', row_to_json(x)::text FROM (SELECT carrosserie, double_commande, matiere_inflammable, codes_categorie FROM site.carrosserie_usage_combinaisons WHERE actif = true) x;

SELECT 'retiré' AS sens, jeu, ligne FROM (SELECT * FROM _api_avant EXCEPT SELECT * FROM _api_apres) a
UNION ALL
SELECT 'ajouté', jeu, ligne FROM (SELECT * FROM _api_apres EXCEPT SELECT * FROM _api_avant) b
ORDER BY jeu, ligne, sens DESC;

