DO $g$
DECLARE n int; l text;
BEGIN
  IF to_regnamespace('referentiel') IS NOT NULL THEN RAISE EXCEPTION '[ÉCHEC]  le schéma referentiel existe déjà'; END IF;

  SELECT count(*), string_agg(DISTINCT c.genre_canonique, ', ') INTO n, l
    FROM site.carrosseries c LEFT JOIN tarification.genre g ON g.libelle = c.genre_canonique
   WHERE g.id_genre IS NULL;
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  genre(s) de carrosserie sans équivalent dans tarification.genre : %', l; END IF;

  SELECT count(*), string_agg(DISTINCT u.genre_canonique, ', ') INTO n, l
    FROM site.genres_usages u LEFT JOIN tarification.genre g ON g.libelle = u.genre_canonique
   WHERE g.id_genre IS NULL AND u.genre_canonique NOT IN ('Camion', 'Minibus', 'Taxi de ville');
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  genre(s) d usage inattendu(s) : %', l; END IF;

  SELECT count(*), string_agg(DISTINCT etat_nom, ', ') INTO n, l FROM site.genres_etats
   WHERE etat_nom NOT IN ('Tonnage', 'Remorque attachée', 'Double Cabine');
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  attribut(s) inattendu(s) : %', l; END IF;

  SELECT count(*), string_agg(code, ', ') INTO n, l
    FROM (SELECT code FROM site.usages_categories GROUP BY code HAVING count(*) > 1) d;
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  code(s) de catégorie en double : %', l; END IF;

  SELECT count(*), string_agg(n2.nspname || '.' || p.proname, ', ') INTO n, l
    FROM pg_proc p JOIN pg_namespace n2 ON n2.oid = p.pronamespace JOIN pg_language lg ON lg.oid = p.prolang
   WHERE lg.lanname <> 'c' AND n2.nspname NOT IN ('pg_catalog', 'information_schema')
     AND p.prosrc ~ '\m(carrosseries|genres_etats|carrosserie_usage_combinaisons|genres_usages)\M';
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  fonction(s) lisant les tables remplacées : %', l; END IF;

  RAISE NOTICE '[OK]     Genres reconnus, codes de catégorie uniques, aucune fonction concernée';
END $g$;

