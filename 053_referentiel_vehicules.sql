CREATE TABLE referentiel.terme_vehicule (
  id_terme_vehicule      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  libelle                varchar(100) NOT NULL UNIQUE,
  id_genre               integer NOT NULL REFERENCES tarification.genre (id_genre),
  code_categorie_imposee varchar(10) REFERENCES site.usages_categories (code),
  actif                  boolean NOT NULL DEFAULT true,
  ordre_affichage        integer NOT NULL DEFAULT 0
);
COMMENT ON TABLE referentiel.terme_vehicule IS 'Lexique des types de véhicules : forme du véhicule, genre canonique principal, catégorie imposée pour un terme directif.';

CREATE TABLE referentiel.terme_vehicule_genre (
  id_terme_vehicule_genre integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_terme_vehicule       integer NOT NULL REFERENCES referentiel.terme_vehicule (id_terme_vehicule),
  id_genre                integer NOT NULL REFERENCES tarification.genre (id_genre),
  code_categorie_defaut   varchar(10) REFERENCES site.usages_categories (code),
  UNIQUE (id_terme_vehicule, id_genre)
);
COMMENT ON TABLE referentiel.terme_vehicule_genre IS 'Genres d un terme qui en a plusieurs (porte-véhicules), avec la catégorie par défaut de chaque couple.';

CREATE TABLE referentiel.attribut_vehicule (
  code_attribut_vehicule varchar(30) PRIMARY KEY,
  libelle                varchar(50) NOT NULL UNIQUE,
  valeurs                jsonb NOT NULL
);
COMMENT ON TABLE referentiel.attribut_vehicule IS 'Attributs d un véhicule et leurs valeurs possibles.';

CREATE TABLE referentiel.terme_vehicule_attribut (
  id_terme_vehicule_attribut integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_terme_vehicule          integer NOT NULL REFERENCES referentiel.terme_vehicule (id_terme_vehicule),
  code_attribut_vehicule     varchar(30) NOT NULL REFERENCES referentiel.attribut_vehicule (code_attribut_vehicule),
  actif                      boolean NOT NULL DEFAULT true,
  ordre_affichage            integer NOT NULL DEFAULT 0,
  UNIQUE (id_terme_vehicule, code_attribut_vehicule)
);

CREATE TABLE referentiel.combinaison_categorie (
  id_combinaison_categorie integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_terme_vehicule        integer NOT NULL REFERENCES referentiel.terme_vehicule (id_terme_vehicule),
  double_commande          varchar(10) CHECK (double_commande IN ('Avec', 'Sans')),
  matiere_inflammable      varchar(10) CHECK (matiere_inflammable IN ('Oui', 'Non')),
  code_categorie           varchar(10) REFERENCES site.usages_categories (code),
  actif                    boolean NOT NULL DEFAULT true,
  ordre_affichage          integer NOT NULL DEFAULT 0,
  UNIQUE NULLS NOT DISTINCT (id_terme_vehicule, double_commande, matiere_inflammable, code_categorie)
);
COMMENT ON TABLE referentiel.combinaison_categorie IS 'Catégories autorisées pour un terme selon la double commande et la matière inflammable ; code vide = aucune catégorie possible.';

CREATE TABLE referentiel.usage_genre (
  id_usage_genre  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_genre        integer NOT NULL REFERENCES tarification.genre (id_genre),
  libelle_usage   varchar(200) NOT NULL,
  code_categorie  varchar(10) NOT NULL REFERENCES site.usages_categories (code),
  actif           boolean NOT NULL DEFAULT true,
  ordre_affichage integer NOT NULL DEFAULT 0,
  UNIQUE (id_genre, libelle_usage, code_categorie)
);
COMMENT ON TABLE referentiel.usage_genre IS 'Libellés d usage proposés à l utilisateur pour un genre, avec leur catégorie.';

