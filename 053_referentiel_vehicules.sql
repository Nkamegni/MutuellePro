\echo '=== 7. Contrôle de cohérence combinaisons <-> usages ==='
CREATE TEMP TABLE _genres_terme AS
SELECT id_terme_vehicule, id_genre FROM referentiel.terme_vehicule
UNION SELECT id_terme_vehicule, id_genre FROM referentiel.terme_vehicule_genre;

DO $c$
DECLARE n int; l text;
BEGIN
  SELECT count(*), string_agg(t.libelle || ' : ' || c.code_categorie, ', ') INTO n, l
    FROM referentiel.combinaison_categorie c
    JOIN referentiel.terme_vehicule t USING (id_terme_vehicule)
   WHERE c.code_categorie IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM _genres_terme gt JOIN referentiel.usage_genre u ON u.id_genre = gt.id_genre
                      WHERE gt.id_terme_vehicule = c.id_terme_vehicule AND u.code_categorie = c.code_categorie);
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  catégorie(s) autorisée(s) sans usage proposé : %', l; END IF;

  SELECT count(*), string_agg(g.libelle || ' : ' || u.code_categorie, ', ') INTO n, l
    FROM referentiel.usage_genre u JOIN tarification.genre g USING (id_genre)
   WHERE NOT EXISTS (SELECT 1 FROM _genres_terme gt JOIN referentiel.combinaison_categorie c USING (id_terme_vehicule)
                      WHERE gt.id_genre = u.id_genre AND c.code_categorie = u.code_categorie);
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  usage(s) proposé(s) sans catégorie autorisée : %', l; END IF;

  SELECT count(*), string_agg(t.libelle, ', ') INTO n, l FROM referentiel.terme_vehicule t
   WHERE NOT EXISTS (SELECT 1 FROM referentiel.combinaison_categorie c WHERE c.id_terme_vehicule = t.id_terme_vehicule);
  IF n > 0 THEN RAISE EXCEPTION '[ÉCHEC]  terme(s) sans aucune combinaison : %', l; END IF;

  RAISE NOTICE '[OK]     Combinaisons et usages cohérents dans les deux sens ; chaque terme a ses combinaisons';
END $c$;

